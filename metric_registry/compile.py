"""Compile registry.yml into the MetricFlow semantic layer and the glossary, and guard metric versions.

    python -m metric_registry.compile           # write dbt/models/semantic/*.yml, GLOSSARY.md, registry.lock.json
    python -m metric_registry.compile --check   # fail if any of them is out of date (CI)

Every metric gets a fingerprint: a hash of what it computes (for a simple metric, its measure's model, time
column, aggregation and expression; for a ratio, its numerator's and denominator's fingerprints).
registry.lock.json keeps the last compiled version and fingerprint of each metric. A fingerprint that
changed under the same version is refused, so no governed number can move without a version bump.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REGISTRY = HERE / "registry.yml"
LOCK = HERE / "registry.lock.json"
GLOSSARY = HERE / "GLOSSARY.md"
SEMANTIC_DIR = HERE / "dbt" / "models" / "semantic"
SEMANTIC_MODELS = SEMANTIC_DIR / "_semantic_models.yml"
METRICS = SEMANTIC_DIR / "_metrics.yml"
HEADER = "# Generated by `python -m metric_registry.compile` from metric_registry/registry.yml. Do not edit.\n"
METRIC_KEYS = {"label", "definition", "owner", "version", "changelog", "measure", "numerator", "denominator"}


class RegistryError(Exception):
    pass


def load_registry(path: Path = REGISTRY) -> dict:
    return yaml.safe_load(path.read_text())


def _entities(sm: dict) -> dict[str, tuple[str, str]]:
    """{entity: (type, column)} from the registry's 'type column' shorthand."""
    out = {}
    for name, spec in sm["entities"].items():
        kind, column = spec.split()
        out[name] = (kind, column)
    return out


def _primary(sm: dict) -> str:
    return next(name for name, (kind, _) in _entities(sm).items() if kind == "primary")


def validate(reg: dict) -> None:
    errors = []
    models = reg["semantic_models"]
    for name, sm in models.items():
        kinds = [k for k, _ in _entities(sm).values()]
        if kinds.count("primary") != 1:
            errors.append(f"semantic model {name}: needs exactly one primary entity")
        if sm.get("measures") and not sm.get("time"):
            errors.append(f"semantic model {name}: has measures but no time column")
    metrics = reg["metrics"]
    for name, m in metrics.items():
        where = f"metric {name}"
        if unknown := set(m) - METRIC_KEYS:
            errors.append(f"{where}: unknown keys {sorted(unknown)}")
        for key in ("label", "definition", "owner"):
            if not str(m.get(key) or "").strip():
                errors.append(f"{where}: missing {key}")
        version = m.get("version")
        if not isinstance(version, int) or version < 1:
            errors.append(f"{where}: version must be a whole number from 1")
        elif version not in (m.get("changelog") or {}):
            errors.append(f"{where}: changelog has no entry for version {version}")
        if "measure" in m:
            model, _, measure = str(m["measure"]).partition(".")
            if measure not in (models.get(model, {}).get("measures") or {}):
                errors.append(f"{where}: no measure {m['measure']}")
            if "numerator" in m or "denominator" in m:
                errors.append(f"{where}: a metric has a measure or a numerator and denominator, not both")
        else:
            for part in ("numerator", "denominator"):
                ref = m.get(part)
                if ref not in metrics or "measure" not in metrics.get(ref, {}):
                    errors.append(f"{where}: {part} must name a simple metric, got {ref!r}")
    if errors:
        raise RegistryError("\n".join(errors))


def fingerprint(reg: dict, name: str) -> str:
    m = reg["metrics"][name]
    if "measure" in m:
        model, _, measure = m["measure"].partition(".")
        sm = reg["semantic_models"][model]
        spec = {"model": sm["model"], "time": sm["time"], **sm["measures"][measure]}
    else:
        spec = {"ratio": [fingerprint(reg, m["numerator"]), fingerprint(reg, m["denominator"])]}
    return hashlib.sha256(json.dumps(spec, sort_keys=True).encode()).hexdigest()[:16]


def dimensions(reg: dict, name: str) -> list[str]:
    """The group-bys MetricFlow allows for a metric: metric_time, the dimensions on its own semantic model
    and on every model whose primary entity it references."""
    m = reg["metrics"][name]
    if "measure" not in m:
        num, den = set(dimensions(reg, m["numerator"])), set(dimensions(reg, m["denominator"]))
        return sorted(num & den)
    models = reg["semantic_models"]
    home = models[m["measure"].partition(".")[0]]
    out = {"metric_time"} | {f"{_primary(home)}__{d}" for d in home["dimensions"]}
    for entity, (kind, _) in _entities(home).items():
        if kind != "foreign":
            continue
        for other in models.values():
            if _primary(other) == entity:
                out |= {f"{entity}__{d}" for d in other["dimensions"]}
    return sorted(out)


def check_versions(reg: dict, lock: dict) -> list[str]:
    """Why the registry cannot be compiled against this lock, one line per metric (empty when it can)."""
    problems = []
    for name, m in reg["metrics"].items():
        fp, version = fingerprint(reg, name), m["version"]
        old = lock.get(name)
        if old is None:
            if version != 1:
                problems.append(f"{name}: a new metric starts at version 1, not {version}")
        elif version < old["version"]:
            problems.append(f"{name}: version went down from {old['version']} to {version}")
        elif fp != old["fingerprint"] and version == old["version"]:
            problems.append(f"{name}: what it computes changed but it is still version {version}; "
                            f"bump it to {version + 1} and add a changelog line")
    for name in sorted(set(lock) - set(reg["metrics"])):
        problems.append(f"{name}: removed from the registry; something may still read it")
    return problems


def _semantic_yaml(reg: dict) -> dict:
    out = []
    for name, sm in reg["semantic_models"].items():
        entities = [{"name": e, "type": kind, "expr": col} for e, (kind, col) in _entities(sm).items()]
        dims = [{"name": d, "type": "categorical"} for d in sm["dimensions"]]
        model = {"name": name, "description": sm["description"], "model": f"ref('{sm['model']}')"}
        if sm.get("time"):
            model["defaults"] = {"agg_time_dimension": sm["time"]}
            dims.insert(0, {"name": sm["time"], "type": "time", "type_params": {"time_granularity": "day"}})
        model["entities"] = entities
        model["dimensions"] = dims
        if sm.get("measures"):
            model["measures"] = [{"name": k, **v} for k, v in sm["measures"].items()]
        out.append(model)
    spine = {"name": "metricflow_time_spine", "description": "Daily calendar for MetricFlow.",
             "time_spine": {"standard_granularity_column": "date_day"},
             "columns": [{"name": "date_day", "granularity": "day"}]}
    return {"version": 2, "models": [spine], "semantic_models": out}


def _metrics_yaml(reg: dict) -> dict:
    out = []
    for name, m in reg["metrics"].items():
        metric = {"name": name, "label": m["label"], "description": m["definition"]}
        if "measure" in m:
            metric |= {"type": "simple", "type_params": {"measure": m["measure"].partition(".")[2]}}
        else:
            metric |= {"type": "ratio", "type_params": {"numerator": m["numerator"], "denominator": m["denominator"]}}
        metric["config"] = {"meta": {"version": m["version"], "owner": m["owner"],
                                     "fingerprint": fingerprint(reg, name)}}
        out.append(metric)
    return {"version": 2, "metrics": out}


def formula(reg: dict, name: str) -> str:
    m = reg["metrics"][name]
    if "measure" not in m:
        return f"{m['numerator']} / {m['denominator']}"
    model, _, measure = m["measure"].partition(".")
    sm = reg["semantic_models"][model]
    spec = sm["measures"][measure]
    return f"{spec['agg']}({spec['expr']}) from {sm['model']} by {sm['time']}"


def _glossary(reg: dict) -> str:
    lines = ["# Glossary", "",
             "Generated by `python -m metric_registry.compile` from [registry.yml](registry.yml). Do not edit.", "",
             "## Terms", "", "| Term | Meaning |", "|---|---|"]
    lines += [f"| {term} | {text} |" for term, text in reg["glossary"].items()]
    lines += ["", "## Metrics", "", "| Metric | Definition | Computed as | Version | Owner |", "|---|---|---|---|---|"]
    for name, m in reg["metrics"].items():
        lines.append(f"| `{name}` ({m['label']}) | {m['definition']} | `{formula(reg, name)}` | {m['version']} "
                     f"| {m['owner']} |")
    lines += ["", "## Group-bys", "", "Every metric can be grouped by `metric_time` (day, week, month, quarter, year).",
              "", "| Metric | Other group-bys |", "|---|---|"]
    for name in reg["metrics"]:
        dims = [f"`{d}`" for d in dimensions(reg, name) if d != "metric_time"]
        lines.append(f"| `{name}` | {', '.join(dims)} |")
    lines += ["", "## Changelog", ""]
    for name, m in reg["metrics"].items():
        for version, note in sorted(m["changelog"].items()):
            lines.append(f"- `{name}` v{version}: {note}")
    return "\n".join(lines) + "\n"


def _dump(data: dict) -> str:
    return HEADER + yaml.safe_dump(data, sort_keys=False, width=110, allow_unicode=True)


def compile_registry(reg: dict) -> dict[Path, str]:
    """Every generated file and its text. Raises RegistryError if the registry is invalid."""
    validate(reg)
    lock = {name: {"version": m["version"], "fingerprint": fingerprint(reg, name)}
            for name, m in reg["metrics"].items()}
    return {SEMANTIC_MODELS: _dump(_semantic_yaml(reg)), METRICS: _dump(_metrics_yaml(reg)),
            GLOSSARY: _glossary(reg), LOCK: json.dumps(lock, indent=2, sort_keys=True) + "\n"}


def read_lock(path: Path = LOCK) -> dict:
    return json.loads(path.read_text()) if path.exists() else {}


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m metric_registry.compile")
    p.add_argument("--check", action="store_true", help="fail if the generated files are out of date")
    args = p.parse_args(argv)
    reg = load_registry()
    try:
        files = compile_registry(reg)
    except RegistryError as e:
        print(f"registry.yml is invalid:\n{e}", file=sys.stderr)
        return 1
    if problems := check_versions(reg, read_lock()):
        print("metric versions need attention:\n" + "\n".join(problems), file=sys.stderr)
        return 1
    if args.check:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        for path in stale:
            print(f"{path.relative_to(HERE)} is out of date: run python -m metric_registry.compile", file=sys.stderr)
        if not stale:
            print(f"{len(reg['metrics'])} metrics: generated files and lock match registry.yml")
        return 1 if stale else 0
    for path, text in files.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(HERE)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
