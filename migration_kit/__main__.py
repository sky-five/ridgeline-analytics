import argparse
import json
import sys
import tempfile
from pathlib import Path

from migration_kit import checklist
from migration_kit.feed import SNAPSHOTS, fetch, snapshots
from migration_kit.reconcile import to_markdown
from migration_kit.replay import RESULTS, compact, replay

HERE = Path(__file__).resolve().parent
DEFAULT_DB = HERE.parent / "warehouse" / "migration.duckdb"

p = argparse.ArgumentParser(prog="python -m migration_kit")
p.add_argument("--db", type=Path, default=DEFAULT_DB)
p.add_argument("--fetch", action="store_true", help="add a fresh snapshot of the feed to snapshots/ first")
p.add_argument("--check", action="store_true", help="fail if the committed results are out of date")
p.add_argument("--live", action="store_true",
               help="replay the committed snapshots plus one fetched now (not saved); fail on any mismatch")
args = p.parse_args()


def report(summary: dict) -> str:
    lines = ["# Reconciliation report", "", "Generated by `python -m migration_kit`; do not edit by hand.", "",
             "## Incremental hash merge vs full reload", ""]
    for ld in summary["hash_merge"]["loads"]:
        lines.append(to_markdown(ld["reconciliation"], f"load {ld['load_id']}, {ld['snapshot']}"))
    lines += ["## Negative control: event-time watermark vs full reload", ""]
    for ld in summary["event_time_watermark"]["loads"]:
        lines.append(to_markdown(ld["reconciliation"], f"load {ld['load_id']}, {ld['snapshot']}"))
    return "\n".join(lines)


if args.live:
    with tempfile.TemporaryDirectory() as tmp:
        live = fetch(Path(tmp))
        paths = snapshots() + [live]
        s = replay(paths)
        for ld in s["hash_merge"]["loads"][-1:]:
            print(to_markdown(ld["reconciliation"], f"live load, {ld['snapshot']}"))
            print({k: ld[k] for k in ("snapshot_rows", "inserted", "updated", "returned", "aged_out", "deleted")})
        bad = [ld["snapshot"] for ld in s["hash_merge"]["loads"] if not ld["reconciliation"]["ok"]]
        sys.exit(f"reconciliation failed on {bad}" if bad else 0)

if args.fetch:
    print("fetched", fetch(SNAPSHOTS).name)
summary = replay(db=args.db)
files = {
    RESULTS / "summary.json": json.dumps(compact(summary), indent=2) + "\n",
    RESULTS / "reconciliation.md": report(summary),
    RESULTS / "retirement_checklist.md": checklist.to_markdown(summary),
}
if args.check:
    stale = [p.name for p, text in files.items() if not p.exists() or p.read_text() != text]
    if stale:
        sys.exit(f"out of date: {', '.join(stale)}; run python -m migration_kit")
    print("results match the committed snapshots")
else:
    RESULTS.mkdir(exist_ok=True)
    for path, text in files.items():
        path.write_text(text)
    t = summary["hash_merge"]["totals"]
    print(f"{len(summary['snapshots'])} snapshots; after the first: " + ", ".join(f"{k} {v}" for k, v in t.items()))
    print(checklist.to_markdown(summary).split("## Column lineage")[0])
