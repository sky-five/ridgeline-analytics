"""Lineage and retirement checklist for legacy.earthquakes.

Each item is checked from the code and the replay results, not ticked by hand. The last two need a person
and stay open until someone signs them off in SIGN_OFF.
"""
import re
from pathlib import Path

from migration_kit.feed import COLUMNS

REPO = Path(__file__).resolve().parent.parent
MIN_CLEAN_LOADS = 3
SCAN_SUFFIXES = {".py", ".sql", ".yml", ".yaml", ".md"}
LEGACY_REF = re.compile(r"\blegacy\.earthquakes\b")

# legacy column -> target column. The target keeps every feed column under its own name and adds bookkeeping.
LINEAGE = {c: c for c in COLUMNS}
TARGET_ONLY = {
    "row_hash": "md5 of the 22 feed columns, used for change capture",
    "in_feed": "false once the event leaves the feed",
    "left_feed_as": "aged_out (older than 30 days) or deleted (dropped inside the window)",
    "first_load_id": "load that first saw the event",
    "last_changed_load_id": "load that last changed a feed column",
    "last_seen_load_id": "last load whose snapshot had the event",
}
SIGN_OFF = {
    "Owners of downstream reports have moved to target.earthquakes": None,
    "legacy.earthquakes dropped after a 14-day grace period": None,
}


def legacy_readers(repo: Path = REPO) -> list[str]:
    """Files outside this folder that still name the legacy table."""
    here = Path(__file__).resolve().parent
    hits = []
    for path in repo.rglob("*"):
        parts = path.relative_to(repo).parts
        skip_dir = any(p.startswith(".") or p in {"node_modules", "target", "build"} for p in parts)
        if skip_dir or path.suffix not in SCAN_SUFFIXES or not path.is_file() or here in path.parents:
            continue
        if LEGACY_REF.search(path.read_text(errors="ignore")):
            hits.append(path.relative_to(repo).as_posix())
    return sorted(hits)


def trailing_clean_loads(loads: list[dict]) -> int:
    n = 0
    for load in reversed(loads):
        if not load["reconciliation"]["ok"]:
            break
        n += 1
    return n


def items(summary: dict, repo: Path = REPO) -> list[tuple[bool, str, str]]:
    target_cols = set(summary["target_columns"])
    loads = summary["hash_merge"]["loads"]
    control = summary["event_time_watermark"]
    clean = trailing_clean_loads(loads)
    control_failed = sum(not ld["reconciliation"]["ok"] for ld in control["loads"])
    readers = legacy_readers(repo)
    unmapped = [c for c, t in LINEAGE.items() if t not in target_cols]
    out = [
        (not unmapped, "Every legacy column has a target column",
         f"{len(LINEAGE)} of {len(LINEAGE)} mapped by name" if not unmapped else f"missing: {', '.join(unmapped)}"),
        (clean >= MIN_CLEAN_LOADS, f"Parallel run: the last {MIN_CLEAN_LOADS}+ loads reconcile with zero differences",
         f"{clean} of {len(loads)} loads in a row, from {loads[0]['snapshot']} to {loads[-1]['snapshot']}"),
        (control_failed > 0,
         "The reconciliation catches a broken loader (event-time watermark run fails)",
         f"failed on {control_failed} of {len(control['loads'])} loads"),
        (summary["history_kept"] > 0 or summary["hash_merge"]["totals"]["aged_out"] == 0,
         "Target keeps rows the legacy table loses",
         f"{summary['history_kept']} events kept after leaving the feed"),
        (not readers, "No code outside migration_kit/ reads legacy.earthquakes",
         "none found" if not readers else ", ".join(readers)),
    ]
    out += [(bool(who), item, who or "needs a person") for item, who in SIGN_OFF.items()]
    return out


def to_markdown(summary: dict, repo: Path = REPO) -> str:
    lines = ["# Retirement checklist: legacy.earthquakes", "",
             "Generated by `python -m migration_kit`; do not edit by hand.", ""]
    for ok, item, detail in items(summary, repo):
        lines.append(f"- [{'x' if ok else ' '}] {item} ({detail})")
    lines += ["", "## Column lineage", "", "| legacy.earthquakes | target.earthquakes |", "|---|---|"]
    lines += [f"| {c} | {t} |" for c, t in LINEAGE.items()]
    lines += ["", "Added in the target:", ""]
    lines += [f"- `{c}`: {why}" for c, why in TARGET_ONLY.items()]
    return "\n".join(lines) + "\n"
