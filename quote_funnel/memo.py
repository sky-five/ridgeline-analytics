"""The one-page decision memo, written from the summary so its numbers are never typed by hand."""


def pct(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}%"


def money(x: float) -> str:
    return f"${x:,.0f}"


def unwrap(text: str) -> str:
    """Join the source's wrapped lines so each paragraph is one line in the file."""
    return "\n\n".join(" ".join(block.split("\n")) for block in text.strip().split("\n\n")) + "\n"


def to_markdown(s: dict) -> str:
    c, n = s["counting_change"], s["new_carrier"]
    req, ses, brk = c["quote_to_bind_per_request"], c["quote_to_bind_per_session"], c["logging_break"]
    e, t = n["estimate"], n["truth"]
    lo, hi = e["added_binds_ci"]
    clo, chi = e["added_commission_ci"]
    lost = sum(e["lost_by_panel"].values())
    return unwrap(f"""# Decision memo: the quote-to-bind drop and the candidate carrier

Generated by `python -m quote_funnel` from simulated data ({s['weeks']}); do not edit by hand.

## 1. Quote-to-bind fell in April. Do we act on it?

**No. The drop is a counting change, not a change in shoppers.** The dashboard's rate (binds per quoted
request) went from {pct(req['before'])} to {pct(req['after'])} from the week of {brk['week']}, a
{-c['relative_drop_per_request_pct']:.0f}% relative fall. That same week the request log went from
{brk['requests_per_session_before']:.2f} to {brk['requests_per_session_after']:.2f} requests per session: edits
and resubmits started being logged as new requests. Sessions ({brk['sessions_per_week_before']:,.0f} vs
{brk['sessions_per_week_after']:,.0f} a week) and binds ({brk['binds_per_week_before']:.0f} vs
{brk['binds_per_week_after']:.0f} a week) did not move. Counted per session, quote-to-bind is
{pct(ses['before'])} before and {pct(ses['after'])} after: {ses['diff_pp']:+.2f} points (95% CI
{ses['ci_pp'][0]:+.2f} to {ses['ci_pp'][1]:+.2f}, p = {ses['p_value']:.2f}). The request count explains
{c['share_of_drop_from_request_count_pct']:.0f}% of the drop.

Action: move the dashboard to the session-level definitions, keep requests per session as a logging health
check with an alert on a step change, and note the break on any chart that spans it.

## 2. Should we add the candidate carrier to the panel?

**Yes, on these numbers.** The candidate priced {e['sample_sessions']:,} past auto sessions and quoted
{e['sample_quoted_by_candidate']:,} of them. Scored with models fitted on the half's clicks and binds, adding it
gives about {e['added_binds']:,.0f} more binds a half-year (95% CI {lo:,.0f} to {hi:,.0f}) and
{money(e['added_commission'])} more commission ({money(clo)} to {money(chi)}). It would write about
{e['candidate_binds']:,.0f} policies, so roughly {lost:,.0f} of those come from carriers already on the panel.
At an assumed {money(n['onboarding_cost_assumed'])} one-off onboarding cost that pays back in about
{n['payback_months']:.1f} months.

Risks: the estimate gives the newcomer the panel's average brand pull, and its prices come from a rating sample,
not live traffic. Launch on a share of auto traffic first and compare bound sessions per quoted session with the
holdout.

Check against the simulator: replaying the same simulated shoppers with the candidate on the panel gives
{t['added_binds']:,} more binds, {money(t['added_commission'])} more commission and {t['candidate_binds']:,}
policies for the candidate. A real team would not have this; it is here to show the method lands near the
truth.
""")
