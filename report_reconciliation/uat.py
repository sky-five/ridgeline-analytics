"""UAT sign-off checklist per report. The automated items are ticked from the check results; the items that
need the report owner stay open until a name and date are filled in SIGN_OFF."""

from report_reconciliation.reports import REPORTS

DEFINITIONS = {
    "project_hours": "hours = approved entries only; cost = hours x the cost rate in effect on the work date",
    "utilisation": "utilisation = billable approved hours / weekly capacity; internal projects are not billable",
    "budget_burn": "burn = cost to date / budget; every project is listed, closed ones too",
}
SIGN_OFF: dict[str, dict[str, str | None]] = {rep.name: {
    "Owner traced the sample rows below back to the source system": None,
    "Owner agrees with the definitions": None,
    "Signed off (name, date)": None,
} for rep in REPORTS}
CHECK_TEXT = {
    "row_count": lambda c: f"Row counts match the source ({c['mart_rows']:,} rows, "
                           f"{c['keys_only_in_mart']} keys only in the mart, "
                           f"{c['keys_only_in_source']} only in source)",
    "totals": lambda c: "Totals match the source (" + "; ".join(
        f"{m} {v['mart']:,.2f} vs {v['source']:,.2f}, {v['keys_differing']} keys off" for m, v in c["measures"].items())
        + ")",
    "refresh_age": lambda c: f"Inputs extracted within {c['sla_hours']} h (oldest "
                             f"{max(c['input_age_hours'].values())} h) and the mart was built from them",
    "lineage": lambda c: f"Lineage documented for all {c['columns']} columns, {c['source_columns']} source columns "
                         "found" + (f"; undocumented: {', '.join(c['undocumented'])}" if c["undocumented"] else ""),
}


def to_markdown(summary: dict) -> str:
    lines = ["# UAT sign-off checklist", "", "Generated by `python -m report_reconciliation`; do not edit by hand. "
             f"Checks run {summary['as_of']}, marts built {summary['built_at']}.", ""]
    for r in summary["reports"]:
        lines += [f"## {r['title']} (`{r['mart']}`)", ""]
        lines += [f"- [{'x' if c['ok'] else ' '}] {CHECK_TEXT[k](c)}" for k, c in r["checks"].items()]
        lines += [f"- [{'x' if who else ' '}] {item} ({who or 'needs the report owner'})"
                  for item, who in SIGN_OFF[r["report"]].items()]
        lines += ["", f"Definitions: {DEFINITIONS[r['report']]}.", "", "Sample rows to trace:", ""]
        rows = summary["samples"][r["report"]]
        cols = list(rows[0])
        lines += ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        lines += ["| " + " | ".join(f"{v:,.2f}" if isinstance(v, float) else str(v) for v in row.values()) + " |"
                  for row in rows]
        lines.append("")
    return "\n".join(lines)
