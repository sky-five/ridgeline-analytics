import argparse
import json
import sys
from pathlib import Path

from report_reconciliation import uat
from report_reconciliation.run import run

RESULTS = Path(__file__).resolve().parent / "results"
MARK = {True: "pass", False: "FAIL"}

p = argparse.ArgumentParser(prog="python -m report_reconciliation")
p.add_argument("--check", action="store_true", help="fail if the committed results are out of date or a check fails")
args = p.parse_args()


def report(summary: dict) -> str:
    lines = ["# Report reconciliation", "", "Generated by `python -m report_reconciliation`; do not edit by hand.", "",
             "| report | mart | row_count | totals | refresh_age | lineage |", "|---|---|---|---|---|---|"]
    for r in summary["reports"]:
        lines.append(f"| {r['title']} | `{r['mart']}` | "
                     + " | ".join(MARK[c["ok"]] for c in r["checks"].values()) + " |")
    lines += ["", "## Planted faults", "", "Each fault is planted on its own; the checks that fail are listed.", "",
              "| fault | " + " | ".join(r["report"] for r in summary["reports"]) + " |",
              "|---|" + "---|" * len(summary["reports"])]
    for fault, by_report in summary["planted_faults"].items():
        lines.append(f"| {fault} | " + " | ".join(", ".join(v) or "all pass" for v in by_report.values()) + " |")
    return "\n".join(lines) + "\n"


summary = run()
files = {
    RESULTS / "summary.json": json.dumps(summary, indent=2, default=str) + "\n",
    RESULTS / "reconciliation.md": report(summary),
    RESULTS / "uat_checklist.md": uat.to_markdown(summary),
}
bad = [r["report"] for r in summary["reports"] if not r["ok"]]
missed = [f for f, by in summary["planted_faults"].items() if not any(by.values())]
if args.check:
    stale = [p.name for p, text in files.items() if not p.exists() or p.read_text() != text]
    problems = ([f"out of date: {', '.join(stale)}; run python -m report_reconciliation"] if stale else []) + \
               ([f"checks failed: {', '.join(bad)}"] if bad else []) + \
               ([f"faults not caught: {', '.join(missed)}"] if missed else [])
    if problems:
        sys.exit("; ".join(problems))
    print("all reports reconcile; every planted fault is caught")
    sys.exit(0)
RESULTS.mkdir(exist_ok=True)
for path, text in files.items():
    path.write_text(text)
print(report(summary))
sys.exit(f"checks failed: {', '.join(bad)}" if bad else 0)
